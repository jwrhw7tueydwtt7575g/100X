from httpx import AsyncClient

from tests.conftest import TEMPLE_LAT, TEMPLE_LON


async def test_marathi_facility_question_returns_nearby_water(client: AsyncClient) -> None:
    response = await client.post(
        "/api/conversation/message",
        json={
            "text": "जवळ पाणी कुठे मिळेल?",
            "location": {"lat": TEMPLE_LAT, "lon": TEMPLE_LON},
        },
    )
    assert response.status_code == 200

    body = response.json()
    assert body["intent"] == "facility"
    assert body["language"] == "mr"
    assert body["source"] == "rules"  # LLM disabled in tests
    assert body["data"]["facilities"], "expected at least one seeded facility"
    assert body["data"]["facilities"][0]["facility_type"] == "water"
    assert any(a["type"] == "show_facilities" for a in body["actions"])


